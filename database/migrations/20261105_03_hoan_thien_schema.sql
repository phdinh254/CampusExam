/* 1. Gỡ khóa ngoại, khóa chính, index và mô tả cũ để dựng lại */
DECLARE @sql nvarchar(max) = N'';

SELECT @sql += N'ALTER TABLE dbo.' + QUOTENAME(OBJECT_NAME(parent_object_id))
             + N' DROP CONSTRAINT ' + QUOTENAME(name) + N';' + NCHAR(10)
  FROM sys.foreign_keys
 WHERE schema_id = SCHEMA_ID(N'dbo');
EXEC sys.sp_executesql @sql;

SET @sql = N'';
SELECT @sql += N'ALTER TABLE dbo.' + QUOTENAME(OBJECT_NAME(parent_object_id))
             + N' DROP CONSTRAINT ' + QUOTENAME(name) + N';' + NCHAR(10)
  FROM sys.key_constraints
 WHERE type = 'PK' AND schema_id = SCHEMA_ID(N'dbo');
EXEC sys.sp_executesql @sql;

SET @sql = N'';
SELECT @sql += N'EXEC sys.sp_dropextendedproperty @name = N''MS_Description'', @level0type = N''SCHEMA'', @level0name = N''dbo'', @level1type = N''TABLE'', @level1name = '
             + QUOTENAME(OBJECT_NAME(major_id), '''')
             + CASE WHEN minor_id = 0 THEN N''
                    ELSE N', @level2type = N''COLUMN'', @level2name = ' + QUOTENAME(COL_NAME(major_id, minor_id), '''') END
             + N';' + NCHAR(10)
  FROM sys.extended_properties
 WHERE class = 1 AND name = N'MS_Description' AND OBJECTPROPERTY(major_id, 'IsUserTable') = 1;
EXEC sys.sp_executesql @sql;

