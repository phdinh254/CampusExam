MERGE dbo.MUCDO AS t
USING (VALUES (CAST(1 AS tinyint), N'Dễ'), (2, N'Trung bình'), (3, N'Khó')) AS s (MAMD, TENMD)
   ON t.MAMD = s.MAMD
WHEN MATCHED AND t.TENMD <> s.TENMD THEN UPDATE SET TENMD = s.TENMD
WHEN NOT MATCHED THEN INSERT (MAMD, TENMD) VALUES (s.MAMD, s.TENMD);
GO

