CREATE TABLE dbo.CAUHOI (
    MACH         int IDENTITY    NOT NULL,
    MALANIMPORT  int             NULL,     -- NULL khi thêm thủ công
    MAMD         tinyint         NOT NULL,
    MAKQHT       int             NOT NULL,
    STT          int             NOT NULL,
    NOIDUNG      nvarchar(4000)  NOT NULL,
    DAA          nvarchar(1000)  NOT NULL,
    DAB          nvarchar(1000)  NOT NULL,
    DAC          nvarchar(1000)  NOT NULL,
    DAD          nvarchar(1000)  NOT NULL,
    DAPANDUNG    char(1)         NOT NULL,
    CODINHDA     smallint        NOT NULL, -- 1: không hoán vị phương án
    TRANGTHAI    smallint        NOT NULL, -- 0 ngừng sử dụng, 1 đang sử dụng
    NGAYTAO      datetime2       NOT NULL,
    NGAYCAPNHAT  datetime2       NULL,
    MACAUHOI     varchar(20)     NOT NULL, -- KYHIEU + MAMD + '-' + STT, VD A1-1
    KYHIEU       char(1)         NOT NULL,
    PHIENBAN     rowversion      NOT NULL,
    CONSTRAINT PK_CAUHOI PRIMARY KEY CLUSTERED (MACH),
    CONSTRAINT AK_AK_CAUHOI_MACAUHOI_CAUHOI UNIQUE (MACAUHOI),
    CONSTRAINT AK_AK_CAUHOI_KQHT_MUC_CAUHOI UNIQUE (MAKQHT, MAMD, STT),
    CONSTRAINT CKT_CAUHOI CHECK ([STT] > 0 AND [DAPANDUNG] COLLATE Latin1_General_100_BIN2 IN ('A','B','C','D') AND [CODINHDA] IN (0,1)),
    CONSTRAINT CKT_CAUHOI_MACAUHOI CHECK (
        MACAUHOI COLLATE Latin1_General_100_BIN2 = KYHIEU + CAST(MAMD AS varchar(1)) + '-' + CAST(STT AS varchar(10))
        AND DATALENGTH(MACAUHOI) = 3 + LEN(CAST(STT AS varchar(10)))),
    CONSTRAINT CKT_CAUHOI_TRANGTHAI CHECK (TRANGTHAI IN (0,1)),
    CONSTRAINT FK_CAUHOI_CO_MUC_DO_MUCDO FOREIGN KEY (MAMD) REFERENCES dbo.MUCDO (MAMD),
    CONSTRAINT FK_CAUHOI_NHAP_TU_LANIMPOR FOREIGN KEY (MALANIMPORT) REFERENCES dbo.LANIMPORT (MALANIMPORT),
    CONSTRAINT FK_CAUHOI_KQHOCTAP_KYHIEU FOREIGN KEY (MAKQHT, KYHIEU) REFERENCES dbo.KQHOCTAP (MAKQHT, KYHIEU)
);
CREATE INDEX CO_MUC_DO_FK ON dbo.CAUHOI (MAMD);
CREATE INDEX NHAP_TU_FK ON dbo.CAUHOI (MALANIMPORT);
